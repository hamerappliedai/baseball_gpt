-- One row per team and season.
with src as (select * from {{ source('lahman', 'teams') }})

select
    yearid::int           as season,
    lgid                  as league_id,
    teamid                as team_id,
    franchid              as franchise_id,
    divid                 as division_id,
    rank::int             as division_rank,
    g::int                as g,
    ghome::int            as g_home,
    w::int                as w,
    l::int                as l,
    (divwin = 'Y')        as won_division,
    (wcwin = 'Y')         as won_wild_card,
    (lgwin = 'Y')         as won_pennant,
    (wswin = 'Y')         as won_world_series,
    r::int                as r,
    ab::int               as ab,
    h::int                as h,
    "2b"::int             as doubles,
    "3b"::int             as triples,
    hr::int               as hr,
    bb::int               as bb,
    so::int               as so,
    sb::int               as sb,
    cs::int               as cs,
    hbp::int              as hbp,
    sf::int               as sf,
    ra::int               as ra,
    er::int               as er,
    era::numeric          as era,
    cg::int               as cg,
    sho::int              as sho,
    sv::int               as sv,
    ipouts::int           as ipouts,
    ha::int               as ha,
    hra::int              as hra,
    bba::int              as bba,
    soa::int              as soa,
    e::int                as e,
    dp::int               as dp,
    fp::numeric           as fp,
    name                  as team_name,
    park                  as park_name,
    attendance::int       as attendance,
    bpf::int              as batting_park_factor,
    ppf::int              as pitching_park_factor,
    teamidbr              as team_id_bbref,
    teamidlahman45        as team_id_lahman45,
    teamidretro           as team_id_retro
from src
