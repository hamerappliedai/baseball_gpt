-- One row per team per season: record, standings, postseason results and
-- team batting/pitching totals.
with t as (select * from {{ ref('stg_teams') }})

select
    t.season,
    t.team_id,
    t.team_name,
    t.franchise_id,
    f.franchise_name,
    t.league_id,
    l.league_name,
    t.division_id,
    t.division_rank,
    t.g,
    t.g_home,
    t.w,
    t.l,
    round(t.w::numeric / nullif(t.w + t.l, 0), 3)                    as win_pct,
    t.r,
    t.ra,
    t.r - t.ra                                                      as run_diff,
    -- Pythagorean expectation (exponent 1.83): win% implied by runs scored/allowed.
    round(power(t.r, 1.83) / nullif(power(t.r, 1.83) + power(t.ra, 1.83), 0)::numeric, 3) as pythag_win_pct,
    t.won_division,
    t.won_wild_card,
    t.won_pennant,
    t.won_world_series,
    t.ab,
    t.h,
    t.doubles,
    t.triples,
    t.hr,
    t.bb,
    t.so,
    t.sb,
    t.cs,
    t.hbp,
    t.sf,
    round(t.h::numeric / nullif(t.ab, 0), 3)                         as avg,
    t.er,
    t.era,
    t.cg,
    t.sho,
    t.sv,
    t.ipouts,
    t.ha,
    t.hra,
    t.bba,
    t.soa,
    t.e,
    t.dp,
    t.fp,
    t.park_name,
    t.attendance,
    t.batting_park_factor,
    t.pitching_park_factor,
    t.team_id_bbref,
    t.team_id_retro
from t
join {{ ref('stg_franchises') }} f using (franchise_id)
join {{ ref('seed_leagues') }} l using (league_id)
